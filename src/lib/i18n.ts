interface I18nState {
  lang: Lang;
  setLang: (l: Lang) => void;
}

export const useI18n = create<I18nState>()(
  persist((set) => ({ lang: "ua", setLang: (l) => set({ lang: l }) }), { name: "terzi-lang" }),
);

export const useT = () => {
  const lang = useI18n((s) => s.lang);
  return (key: keyof typeof dict | string) => {
    const v = dict[key as keyof typeof dict];
    return v ? v[lang] : (key as string);
  };
};
